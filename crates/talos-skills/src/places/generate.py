"""Regenerates the zone table (zones.rs) and its test fixture
(transitions.txt) from the IANA tzdata installed at /usr/share/zoneinfo.

Development-time only (docs/DEVELOPMENT.md, "Zone data"): the binary never
reads the host's zoneinfo. For each zone named in table.rs it takes the
POSIX TZ rule that zic appends to the compiled TZif file (the rule for every
year after the file's listed transitions); the fixture lists every change of
offset in a span of years as Python's zoneinfo computes it from the full
database, which a test compares with the table.

Usage, from the repository root:

    python3 -I crates/talos-skills/src/places/generate.py 2027 2036
"""
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

HERE = Path(__file__).resolve().parent
ZONEINFO = Path('/usr/share/zoneinfo')


def footer(zone):
    data = (ZONEINFO / zone).read_bytes()
    assert data[:4] == b'TZif' and data[-1:] == b'\n', zone
    start = data.rindex(b'\n', 0, len(data) - 1)
    return data[start + 1:-1].decode()


def offset(zi, t):
    return int(datetime.fromtimestamp(t, zi).utcoffset().total_seconds())


def main(first, last):
    places = (HERE / 'table.rs').read_text(encoding='utf-8')
    zones = sorted(set(re.findall(r'"([A-Z][a-z]+/[A-Za-z_/-]+)"', places)))
    version = (ZONEINFO / '+VERSION').read_text().strip()

    with open(HERE / 'zones.rs', 'w', encoding='utf-8') as f:
        f.write('//! Time-zone rules: for each IANA zone the places table uses, its POSIX TZ\n')
        f.write('//! rule (the footer of its compiled `TZif` file), from IANA tzdata %s.\n' % version)
        f.write('//! Generated by generate.py; see docs/DEVELOPMENT.md ("Zone data").\n\n')
        f.write('/// (IANA zone, POSIX TZ rule), sorted by zone.\n')
        f.write('pub(super) const ZONES: &[(&str, &str)] = &[\n')
        for zone in zones:
            f.write('    ("%s", "%s"),\n' % (zone, footer(zone)))
        f.write('];\n')

    start = int(datetime(first, 1, 1, tzinfo=timezone.utc).timestamp())
    end = int(datetime(last + 1, 1, 1, tzinfo=timezone.utc).timestamp())
    step = 3 * 3600
    with open(HERE / 'transitions.txt', 'w', encoding='utf-8') as f:
        f.write('# zone, then "start offset", then "unix offset" at each change, %d-%d,\n' % (first, last))
        f.write('# computed with Python zoneinfo from IANA tzdata %s (generate.py).\n' % version)
        for zone in zones:
            zi = ZoneInfo(zone)
            current = offset(zi, start)
            f.write('%s %d %d\n' % (zone, start, current))
            t = start
            while t < end:
                n = min(t + step, end)
                o = offset(zi, n)
                if o != current:
                    lo, hi = t, n
                    while hi - lo > 1:
                        mid = (lo + hi) // 2
                        if offset(zi, mid) == current:
                            lo = mid
                        else:
                            hi = mid
                    f.write('%s %d %d\n' % (zone, hi, o))
                    current = o
                t = n


if __name__ == '__main__':
    main(int(sys.argv[1]), int(sys.argv[2]))

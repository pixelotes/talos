//! The gazetteer: cities and regions (countries, a few states and islands)
//! with their Spanish and English names and their time zone.
//!
//! Compiled by hand from public facts (capitals, the largest cities, the
//! places the specification names), not from a downloaded dataset. Names
//! are in the match form: lower case, no accents, `ñ` as `n`. Each entry has
//! three name lists, `|`-separated: Spanish names, English names, and names
//! that are the same in both languages; which list matched decides the
//! language of the name Talos writes back (docs/spec/state.md: "qué hora es
//! in Tokyo" answers "En Tokyo…").
//!
//! A name may belong to several entries ("cordoba": Spain and Argentina);
//! the handler then asks which one when they differ. Every city's region
//! code is in [`REGIONS`], and every zone is in `zones::ZONES` (tests check
//! both).

#![allow(
    clippy::similar_names,
    reason = "Spanish and English fields side by side"
)]

/// A city.
#[derive(Debug)]
pub(super) struct City {
    /// Display name in Spanish.
    pub(super) es: &'static str,
    /// Display name in English.
    pub(super) en: &'static str,
    /// The region it is in: a code of [`REGIONS`].
    pub(super) region: &'static str,
    /// Its IANA time zone.
    pub(super) zone: &'static str,
    /// Spanish names, `|`-separated, in the match form.
    pub(super) names_es: &'static str,
    /// English names.
    pub(super) names_en: &'static str,
    /// Names shared by both languages.
    pub(super) names: &'static str,
}

/// What a region's time is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Target {
    /// Its capital's: the city with this English display name.
    Capital(&'static str),
    /// One zone, answered with the region's own name (islands, states).
    Zone(&'static str),
    /// Several zones and no city that stands for them: ask which city.
    Several,
    /// Spain: the peninsula and the Canary Islands, both given.
    Spain,
}

/// A country or another named region.
#[derive(Debug)]
pub(super) struct Region {
    /// ISO 3166-1 code, or `US-XX` for a US state.
    pub(super) code: &'static str,
    /// Display name in Spanish.
    pub(super) es: &'static str,
    /// Display name in English.
    pub(super) en: &'static str,
    /// Its time.
    pub(super) target: Target,
    /// Spanish names, `|`-separated, in the match form.
    pub(super) names_es: &'static str,
    /// English names.
    pub(super) names_en: &'static str,
    /// Names shared by both languages.
    pub(super) names: &'static str,
    /// Adjectives, only for choosing among same-named cities ("la
    /// argentina", "the Spanish one").
    pub(super) adjectives: &'static str,
}

const fn c(
    es: &'static str,
    en: &'static str,
    region: &'static str,
    zone: &'static str,
    names_es: &'static str,
    names_en: &'static str,
    names: &'static str,
) -> City {
    City {
        es,
        en,
        region,
        zone,
        names_es,
        names_en,
        names,
    }
}

#[allow(clippy::too_many_arguments, reason = "a table row")]
const fn r(
    code: &'static str,
    es: &'static str,
    en: &'static str,
    target: Target,
    names_es: &'static str,
    names_en: &'static str,
    names: &'static str,
    adjectives: &'static str,
) -> Region {
    Region {
        code,
        es,
        en,
        target,
        names_es,
        names_en,
        names,
        adjectives,
    }
}

